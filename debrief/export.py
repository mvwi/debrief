"""Export weak Jev questions as jev-align datasets, and read accepted definitions back.

Writes data/jevalign/datasets/<question>.jsonl with rows {"id", "state"}, where state is the exact
string classify.py sends to Jev, plus data/jevalign/<question>.sh with the matching
`jeva optimize` command. Reads debrief.db read-only.

    uv run python -m debrief.export                                   # write all files
    uv run python -m debrief.export --import .jev-align/runs/<run-id>  # print the accepted definition

The loop, per question:
  1. uv run python -m debrief.export
  2. bash data/jevalign/<question>.sh  (needs jeva from the patched jev-align checkout:
     uv tool install --editable ../jev-align). It starts an interactive jeva session.
  3. Label the rows jeva picks; review GEPA's proposal and accept or reject it.
  4. uv run python -m debrief.export --import .jev-align/runs/<run-id>
     jeva writes each run to .jev-align/runs/<timestamp>-<slug>/. Its state.json holds
     current_candidate, the definition last accepted (the seed until you accept one),
     as {instructions, true_criteria, false_criteria} for binary questions or
     {instructions, criteria: {name: description}} for multiclass ones. The command
     prints it as a classify.py noul(...) or choice(...) call.
  5. Paste that over the question in classify.py, then rerun
     `uv run python -m debrief.classify --only turns` (or `--only events` for held_up); the changed
     questions change input_hash, so those items get relabeled.

The scripts pass --raw-text with the single --column state, so jeva sends each row's
state to Jev as the same bare string classify.py sends.
"""

import argparse
import json
import shlex
import sqlite3
from pathlib import Path

from debrief.classify import (
    FOUND_NOT_FILED,
    REVIEW_QUESTIONS,
    TURN_QUESTIONS,
    event_items,
    session_items,
)
from debrief.db import DB_PATH
from debrief.paths import HOME

OUT = HOME / "jevalign"
# Datasets live apart from the run scripts: transcripts are full of backticks and $(...),
# so running a .jsonl by mistake with bash would execute them.
DATA = OUT / "datasets"
# GEPA rewrites definitions through headless Claude Code (Opus 5.5) on the Claude
# subscription; Jev evaluation still runs on OpenRouter.
REFLECTION_MODEL = "claude-code"
# GEPA metric calls per round (jeva defaults to 300); lower caps subscription use.
MAX_METRIC_CALLS = 100

# question name -> (definition, which item kinds carry it)
EXPORTS = {
    "found_not_filed": (FOUND_NOT_FILED, ("turns", "tails")),
    "agent_could_have_found_it": (TURN_QUESTIONS["agent_could_have_found_it"], ("turns",)),
    "design_reversal": (TURN_QUESTIONS["design_reversal"], ("turns",)),
    "human_caught_defect": (TURN_QUESTIONS["human_caught_defect"], ("turns",)),
    "held_up": (REVIEW_QUESTIONS["held_up"], ("review_comments",)),
}


def row_id(it: dict) -> str:
    return ":".join(str(k) for k in it["key"])


def optimize_command(name: str, question: dict, rows: int) -> str:
    lines = [
        ["jeva", "optimize", f"{DATA}/{name}.jsonl"],
        ["--backend", "openrouter"],
        ["--column", "state"],
        ["--raw-text"],
        ["--reflection-model", REFLECTION_MODEL],
        ["--max-metric-calls", str(MAX_METRIC_CALLS)],
        ["--question", question["instructions"]],
    ]
    if question["type"] == "noul":
        lines += [["--true-criteria", question["criteria"]["true"]],
                  ["--false-criteria", question["criteria"]["false"]]]
    elif question["type"] == "choice":
        lines += [["--class", f"{label}={description}"] for label, description in question["criteria"].items()]
    else:
        raise ValueError(f"{name}: {question['type']} questions are not exported")
    lines += [["--holdout"], ["--pool-size", str(max(rows, 5))]]
    return " \\\n  ".join(shlex.join(line) for line in lines)


def write_script(name: str, question: dict, rows: int) -> Path:
    path = OUT / f"{name}.sh"
    path.write_text(
        "#!/usr/bin/env bash\n"
        "# Generated by export.py. Runs from the insights root so runs land in .jev-align/runs.\n"
        "set -euo pipefail\n"
        'cd "$(dirname "$0")/../.."\n'
        "set -a; . ./.env; set +a\n"
        f"{optimize_command(name, question, rows)}\n"
    )
    path.chmod(0o755)
    return path


def export() -> None:
    conn = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True, timeout=30)
    conn.row_factory = sqlite3.Row
    turns, tails, _ = session_items(conn, None)
    reviews, _ = event_items(conn)
    kinds = {"turns": turns, "tails": tails, "review_comments": reviews}

    DATA.mkdir(parents=True, exist_ok=True)
    for name, (question, sources) in EXPORTS.items():
        # Only items where classify.py asks this question; opening turns skip some.
        items = [it for kind in sources for it in kinds[kind] if name in it["questions"]]
        with (DATA / f"{name}.jsonl").open("w") as f:
            for it in items:
                f.write(json.dumps({"id": row_id(it), "state": it["state"]}, ensure_ascii=False) + "\n")
        write_script(name, question, len(items))
        print(f"{name}: {len(items)} rows -> {DATA / name}.jsonl, {OUT / name}.sh")


def import_definition(run_dir: str | Path) -> str:
    """Return the run's accepted definition as classify.py source."""
    state = json.loads((Path(run_dir) / "state.json").read_text())
    spec = state["current_candidate"]
    if "true_criteria" in spec:
        source = (f"noul(\n    {spec['instructions']!r},\n    {spec['true_criteria']!r},\n"
                  f"    {spec['false_criteria']!r},\n)")
    elif isinstance(spec.get("criteria"), dict):
        lines = [f"    {spec['instructions']!r},"]
        lines += [f"    {label}={description!r}," for label, description in spec["criteria"].items()]
        source = "choice(\n" + "\n".join(lines) + "\n)"
    else:
        raise ValueError("only binary and multiclass definitions map to classify.py questions")
    accepted = sum(1 for h in state.get("history", []) if h.get("decision") == "accepted")
    note = f"# {accepted} accepted proposal(s) in {state['run_id']}"
    if not accepted:
        note += "; this is still the seed definition"
    if state.get("pending_candidate"):
        note += "; a proposal awaits review (resume the run to accept or reject it)"
    return f"{note}\n{source}"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--import", dest="run_dir", metavar="RUN_DIR",
                        help="Print the accepted definition of a jeva run as classify.py source")
    args = parser.parse_args(argv)
    if args.run_dir:
        print(import_definition(args.run_dir))
    else:
        export()


if __name__ == "__main__":
    main()
